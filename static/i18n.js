  const ORIGINAL_TEXT = new WeakMap();
  const ORIGINAL_ATTRIBUTES = new WeakMap();
  let locale = "zh-CN";

  function translate(value) {
    const source = String(value ?? "");
    if (locale !== "en") return source;
    // Status panels often put several independently translatable lines in one
    // text node. Keep line breaks and translate each line by the same rules.
    if (source.includes("\n")) return source.split("\n").map(translate).join("\n");
    const leading = source.match(/^\s*/)?.[0] || "";
    const trailing = source.match(/\s*$/)?.[0] || "";
    const core = source.trim();
    if (Object.prototype.hasOwnProperty.call(EN, core)) return leading + EN[core] + trailing;
    for (const [pattern, render] of [...PATTERNS_EXTRA, ...PATTERNS]) {
      const match = core.match(pattern);
      if (match) return leading + render(...match) + trailing;
    }
    return source;
  }

  function isProtected(element) {
    return !!element?.closest(
      'script,style,[contenteditable="true"],[data-i18n-ignore],[translate="no"],.user-content,.source-content,.translation-content,.unit-preview,.source-text,.unit-title,.unit-copy p,.text-columns p,.text-box p:not(.hash-line):not(.editor-draft-hint),.detail-title-row h2,.detail-heading h2,.concept-item strong,.group-copy strong,.cmp-item header strong,.cmp-row dd,.batch-item header strong,.batch-item dd,.batch-line,.evidence blockquote,.meaning,.translation-chip,.concept-fields section p',
    );
  }

  function applyText(node) {
    const parent = node.parentElement;
    if (!parent || parent.closest("textarea,input") || isProtected(parent)) return;
    const previous = ORIGINAL_TEXT.get(node);
    const current = node.data;
    const source = previous && current === previous.applied ? previous.source : current;
    const translated = translate(source);
    if (translated !== current) {
      ORIGINAL_TEXT.set(node, { source, applied: translated });
      node.data = translated;
    } else if (previous) {
      ORIGINAL_TEXT.set(node, { source, applied: current });
    }
  }

  function applyAttribute(element, name) {
    if (isProtected(element) || !element.hasAttribute(name)) return;
    let states = ORIGINAL_ATTRIBUTES.get(element);
    if (!states) {
      states = new Map();
      ORIGINAL_ATTRIBUTES.set(element, states);
    }
    const state = states.get(name);
    const current = element.getAttribute(name);
    const source = state && current === state.applied ? state.source : current;
    const translated = translate(source);
    if (translated !== current) {
      states.set(name, { source, applied: translated });
      element.setAttribute(name, translated);
    } else if (state) {
      states.set(name, { source, applied: current });
    }
  }

  function visit(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      applyText(node);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE) return;
    if (node.nodeType === Node.ELEMENT_NODE && isProtected(node)) return;
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) applyText(textNode);
    if (node.nodeType === Node.ELEMENT_NODE) {
      for (const name of ["placeholder", "title", "aria-label", "aria-description"]) {
        applyAttribute(node, name);
      }
      node.querySelectorAll("*").forEach((element) => {
        if (isProtected(element)) return;
        for (const name of ["placeholder", "title", "aria-label", "aria-description"]) {
          applyAttribute(element, name);
        }
      });
    }
  }

